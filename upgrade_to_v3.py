def git(root: Path, *args: str, check: bool = True) -> subprocess.CompletedProcess[str]:
    command = ["git", "-c", f"safe.directory={root}", "-C", str(root), *args]
    result = subprocess.run(command, text=True, encoding="utf-8", errors="replace",
                            stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    if check and result.returncode:
        detail = result.stderr.strip() or result.stdout.strip()
        raise RuntimeError(f"Command failed ({' '.join(args)}): {detail}")
    return result


def canonical_remote(value: str) -> str:
    value = value.strip()
    if value.startswith("git@github.com:"):
        value = "https://github.com/" + value.split(":", 1)[1]
    return value.rstrip("/").removesuffix(".git").lower()


def contained_path(root: Path, relative: str) -> Path:
    candidate = (root / relative).resolve()
    if candidate == root or root not in candidate.parents:
        raise RuntimeError(f"Refusing a path outside the repository: {relative}")
    return candidate


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate the V3 project and push its release tag.")
    parser.add_argument("--repo-root", type=Path, help="Existing local shopify clone; defaults to this file's folder.")
    args = parser.parse_args()
    root = (args.repo_root or Path(__file__).resolve().parent).expanduser().resolve()
    if not root.is_dir():
        raise RuntimeError(f"Repository directory does not exist: {root}")

    discovered = Path(git(root, "rev-parse", "--show-toplevel").stdout.strip()).resolve()
    if discovered != root:
        raise RuntimeError(f"Run from the repository root ({discovered}), or pass --repo-root explicitly.")
    branch = git(root, "symbolic-ref", "--quiet", "--short", "HEAD").stdout.strip()
    if branch != "main":
        raise RuntimeError(f"Expected branch 'main'; current branch is {branch!r}. Switch to main and retry.")
    remote = git(root, "remote", "get-url", "origin").stdout.strip()
    if canonical_remote(remote) != canonical_remote(EXPECTED_REMOTE):
        raise RuntimeError(f"origin points to {remote!r}; expected the existing repository {EXPECTED_REMOTE!r}.")

    existing_tag = git(root, "rev-parse", "--verify", "--quiet", f"refs/tags/{RELEASE_TAG}", check=False)
    if existing_tag.returncode == 0:
        raise RuntimeError(f"Local tag {RELEASE_TAG} already exists. This script never replaces published tags.")

    own_script = Path(__file__).resolve()
    try:
        own_relative = own_script.relative_to(root).as_posix()
    except ValueError:
        own_relative = None
    status = git(root, "status", "--porcelain", "--untracked-files=all").stdout.splitlines()
    unrelated = []
    for line in status:
        path = line[3:].strip().strip('"')
        if line.startswith("?? ") and own_relative and path.replace("\\", "/") == own_relative:
            continue
        unrelated.append(line)
    if unrelated:
        raise RuntimeError("The checkout has unrelated local changes. Commit, stash, or restore them first:\n  "
                           + "\n  ".join(unrelated))

    for relative, contents in PROJECT_FILES.items():
        target = contained_path(root, relative)
        if target.is_symlink():
            raise RuntimeError(f"Refusing to replace a symbolic link: {relative}")
        target.parent.mkdir(parents=True, exist_ok=True)
        with tempfile.NamedTemporaryFile("w", encoding="utf-8", newline="\n",
                                         dir=target.parent, delete=False) as temporary:
            temporary.write(contents)
            temporary.flush()
            os.fsync(temporary.fileno())
            temp_name = temporary.name
        os.replace(temp_name, target)

    # Remove only known V2-owned code and generator paths, after verifying containment.
    for relative in OBSOLETE_PATHS:
        target = contained_path(root, relative)
        if target.is_symlink():
            raise RuntimeError(f"Refusing to remove a symbolic link: {relative}")
        if target.is_dir():
            shutil.rmtree(target)
        elif target.is_file():
            target.unlink()

    # If the master script was downloaded outside the clone, put a copy in the commit.
    destination = root / "upgrade_to_v3.py"
    if own_script != destination.resolve():
        shutil.copy2(own_script, destination)

    git(root, "diff", "--check")
    git(root, "add", ".")
    staged = git(root, "diff", "--cached", "--quiet", check=False)
    if staged.returncode == 0:
        raise RuntimeError("The V3 project produced no changes; refusing to create an empty release commit.")
    git(root, "diff", "--cached", "--check")
    # Fresh clones can lack author settings; inherit the repository's last author.
    if not git(root, "config", "user.name", check=False).stdout.strip():
        name = git(root, "log", "-1", "--format=%an").stdout.strip()
        if name:
            git(root, "config", "--local", "user.name", name)
    if not git(root, "config", "user.email", check=False).stdout.strip():
        email = git(root, "log", "-1", "--format=%ae").stdout.strip()
        if email:
            git(root, "config", "--local", "user.email", email)
    git(root, "commit", "-m", COMMIT_MESSAGE)
    git(root, "tag", RELEASE_TAG)
    git(root, "push", "origin", "main", "--tags")
    print(f"Published {RELEASE_TAG} to {EXPECTED_REMOTE}")
    print("GitHub Actions will build and attach OmniStoreAIManager.exe to the release.")
    return 0


